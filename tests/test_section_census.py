"""Contract between reproduce_v108.py and main.tex.

The manuscript quotes the script by section number (``section~38 of
\\code{reproduce_v108.py}``) and by figure (``Generated by section~12``),
so the numbering itself is part of the paper: this module pins it down.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from kkgt.constants import FIGURES, SLOW_SECTIONS
from kkgt.harness import REPO_ROOT

TEX = (REPO_ROOT / "main.tex").read_text(encoding="utf-8")

# Every number main.tex cites as "section~N [of \code{reproduce_v108.py}]"
# or "sections~40 and~41".
CITED_IN_TEX = {
    int(n)
    for m in re.finditer(r"sections?~(\d+)(?:\s+and~(\d+))?", TEX)
    for n in m.groups()
    if n
}

# The five figures: file name included by main.tex and section that writes it.
FIGURE_SECTIONS = set(FIGURES)


@pytest.mark.section
class TestSectionRegistry:
    def test_forty_three_sections_in_order(self, sections):
        """Sections 1..43, contiguous: the tex cites them by number."""
        numbers = [n for n, _t, _f in sections]
        assert numbers == list(range(1, 44)), numbers

    def test_every_section_is_callable(self, sections):
        for n, title, fn in sections:
            assert callable(fn), n
            assert title.strip(), n
            assert fn.__name__ == f"seccion_{n}", (n, fn.__name__)

    def test_titles_are_unique(self, sections):
        titles = [t for _n, t, _f in sections]
        assert len(set(titles)) == len(titles)

    def test_section_function_body_has_an_identity(self, repro, sections):
        """Each function carries the section banner in its docstring or
        source header, so a reader can map code -> number without the tex."""
        for n, _title, fn in sections:
            doc = (fn.__doc__ or "").strip()
            src = Path(fn.__code__.co_filename).read_text(encoding="utf-8")
            banner = re.search(
                rf"^# {n}\. .*$", src, re.M
            )
            assert doc or banner, f"section {n} has no docstring nor banner"


@pytest.mark.section
class TestTexCitations:
    def test_tex_cites_only_existing_sections(self, sections):
        numbers = {n for n, _t, _f in sections}
        missing = sorted(CITED_IN_TEX - numbers)
        assert not missing, f"main.tex cites sections that do not exist: {missing}"

    def test_tex_citation_set_is_pinned(self):
        """The exact set of sections the manuscript refers to.

        A change here means main.tex (or the script) moved a citation: check
        the section numbering is still what the paper claims.
        """
        assert CITED_IN_TEX == {2, 10, 12, 13, 29, 36, 37, 38, 39, 40, 41, 42, 43}

    def test_every_figure_section_is_cited(self):
        """Each of the five figures is attributed to a numbered section."""
        assert FIGURE_SECTIONS <= CITED_IN_TEX

    def test_tex_includes_the_five_figure_files(self):
        for name in FIGURES.values():
            assert name in TEX, f"main.tex does not include {name}"


@pytest.mark.section
@pytest.mark.figure
class TestFigureSections:
    @pytest.mark.parametrize(
        "n",
        [
            pytest.param(
                n,
                marks=pytest.mark.slow if n in SLOW_SECTIONS else (),
                id=f"section-{n:02d}",
            )
            for n in sorted(FIGURES)
        ],
    )
    def test_section_writes_its_figure(self, run_section, n):
        run = run_section(n)
        assert FIGURES[n] in run.figures, (
            f"section {n} wrote {run.figures}, expected {FIGURES[n]}"
        )

    def test_slow_figure_sections_are_declared(self):
        """Sections 12 and 41 render >10 s and carry the slow mark."""
        assert FIGURE_SECTIONS & SLOW_SECTIONS == {12, 41}
